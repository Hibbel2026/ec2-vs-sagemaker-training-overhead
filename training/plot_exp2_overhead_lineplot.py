epochs   = np.arange(1, n_epochs + 1)

fig, ax = plt.subplots(figsize=(11, 5))

# EC2
ax.plot(epochs, ec2_mean, color='#457B9D', linewidth=1.8,
        label='EC2 (g5.xlarge)', zorder=3)
ax.fill_between(epochs,
                ec2_mean - ec2_std,
                ec2_mean + ec2_std,
                color='#457B9D', alpha=0.2, zorder=2)

# SageMaker
ax.plot(epochs, sm_mean, color='#E63946', linewidth=1.8,
        label='SageMaker (ml.g5.xlarge)', zorder=3)
ax.fill_between(epochs,
                sm_mean - sm_std,
                sm_mean + sm_std,
                color='#E63946', alpha=0.2, zorder=2)

# Horisontella medelvärdeslinjer
ax.axhline(ec2_mean.mean(), color='#457B9D', linewidth=1,
           linestyle='--', alpha=0.7,
           label=f'EC2 mean: {ec2_mean.mean():.0f} ms')
